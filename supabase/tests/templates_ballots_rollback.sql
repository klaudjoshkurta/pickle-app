-- Authenticated identities exercise RLS and RPCs. No fixtures survive this transaction.
begin;
do $test$
declare
 owner_id uuid:=gen_random_uuid(); guest_id uuid:=gen_random_uuid();
 source_id uuid; template_id uuid; reused_id uuid; multi_id uuid; locked_id uuid;
 request_id uuid:=gen_random_uuid(); ids uuid[]; caught boolean; before_round integer;
begin
 insert into auth.users(id,email) values(owner_id,owner_id::text||'@pickle-test.invalid'),(guest_id,guest_id::text||'@pickle-test.invalid');
 set local role authenticated;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 source_id:=public.create_poll_v2('Source',array['First','Second','Third'],true,true,false,true,now()+interval '1 day',null,gen_random_uuid(),'SINGLE');
 select array_agg(id order by position) into ids from public.poll_options where poll_id=source_id;
 if (select array_agg(text order by position) from public.poll_options where poll_id=source_id)<>array['First','Second','Third'] then raise exception 'Option ordering lost'; end if;
 perform public.cast_ballot(source_id,array[ids[1]]);
 perform public.cast_vote(source_id,ids[2]);
 if (select voter_count from public.polls where id=source_id)<>1 or (select count(*) from public.votes where poll_id=source_id)<>1 then raise exception 'Legacy replacement changed voters'; end if;
 template_id:=public.save_poll_template(source_id,'Weekly film','film',5,'20:00','Europe/Athens');
 if public.save_poll_template(source_id,'Weekly film','film',5,'20:00','Europe/Athens')<>template_id then raise exception 'Duplicate template'; end if;
 if (select template_round from public.polls where id=source_id)<>1 then raise exception 'Source is not round one'; end if;
 reused_id:=public.create_poll_v2('Round two',array['Second','First'],true,true,false,true,now()+interval '7 days',null,request_id,'MULTIPLE',template_id);
 if public.create_poll_v2('Round two',array['Second','First'],true,true,false,true,now()+interval '7 days',null,request_id,'MULTIPLE',template_id)<>reused_id then raise exception 'Duplicate request'; end if;
 if (select rounds_count from public.poll_templates where id=template_id)<>2 or (select template_round from public.polls where id=reused_id)<>2 then raise exception 'Retry incremented history'; end if;
 if (select count(*) from public.notifications where poll_id=reused_id and type='POLL_CREATED')<>1 then raise exception 'Duplicate creation notification'; end if;
 caught:=false;
 begin perform public.create_poll_v2('Invalid round',array['same','SAME'],true,true,false,true,null,null,gen_random_uuid(),'SINGLE',template_id);
 exception when raise_exception then caught:=true; end;
 if not caught or (select rounds_count from public.poll_templates where id=template_id)<>2 then raise exception 'Failed creation changed history'; end if;
 caught:=false;
 begin update public.polls set voter_count=999 where id=source_id;
 exception when insufficient_privilege then caught:=true; end;
 if not caught then raise exception 'Forged voter count accepted'; end if;
 caught:=false;
 begin update public.poll_options set vote_count=999 where id=ids[1];
 exception when insufficient_privilege then caught:=true; end;
 if not caught then raise exception 'Forged option count accepted'; end if;
 multi_id:=public.create_poll_v2('Multi',array['A','B','C'],true,true,false,true,null,null,gen_random_uuid(),'MULTIPLE');
 locked_id:=public.create_poll_v2('Locked',array['A','B'],false,true,false,false,null,null,gen_random_uuid(),'MULTIPLE');
 perform set_config('request.jwt.claim.sub',guest_id::text,true);
 if exists(select 1 from public.poll_templates) then raise exception 'Private template visible'; end if;
 caught:=false;
 begin perform public.save_poll_template(source_id,'Stolen','film',null,null,'UTC');
 exception when insufficient_privilege then caught:=true; end;
 if not caught then raise exception 'Nonowner template save accepted'; end if;
 caught:=false;
 begin perform public.create_poll_v2('Stolen',array['A','B'],false,true,false,true,null,null,gen_random_uuid(),'SINGLE',template_id);
 exception when insufficient_privilege then caught:=true; end;
 if not caught then raise exception 'Nonowner template reuse accepted'; end if;
 select array_agg(id order by position) into ids from public.poll_options where poll_id=multi_id;
 perform public.cast_ballot(multi_id,array[ids[1],ids[2]]);
 perform public.cast_ballot(multi_id,array[ids[2],ids[1]]);
 if (select voter_count from public.polls where id=multi_id)<>1 or (select sum(vote_count) from public.poll_options where poll_id=multi_id)<>2 then raise exception 'Duplicate ballot counted'; end if;
 perform public.cast_ballot(multi_id,array[ids[2],ids[3]]);
 if (select vote_count from public.poll_options where id=ids[1])<>0 or (select vote_count from public.poll_options where id=ids[2])<>1 or (select vote_count from public.poll_options where id=ids[3])<>1 then raise exception 'Ballot replacement not atomic'; end if;
 caught:=false;
 begin perform public.cast_vote(multi_id,ids[1]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Legacy multi-choice vote accepted'; end if;
 caught:=false;
 begin perform public.cast_ballot(multi_id,array[ids[1],ids[1]]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Duplicate option accepted'; end if;
 caught:=false;
 begin perform public.cast_ballot(multi_id,'{}'::uuid[]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Empty ballot accepted'; end if;
 caught:=false;
 begin perform public.cast_ballot(source_id,array[ids[1]]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Cross-poll option accepted'; end if;
 select array_agg(id order by position) into ids from public.poll_options where poll_id=locked_id;
 perform public.cast_ballot(locked_id,array[ids[1]]);
 perform public.cast_ballot(locked_id,array[ids[1]]);
 caught:=false;
 begin perform public.cast_ballot(locked_id,array[ids[2]]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Locked ballot changed'; end if;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 if exists(select 1 from public.poll_ballots where poll_id=multi_id) then raise exception 'Other voter ballot leaked'; end if;
 select array_agg(id order by position) into ids from public.poll_options where poll_id=multi_id;
 perform public.cast_ballot(multi_id,array[ids[1],ids[2],ids[3]]);
 if (select voter_count from public.polls where id=multi_id)<>2 or (select sum(vote_count) from public.poll_options where poll_id=multi_id)<>5 then raise exception 'Voters confused with selections'; end if;
 -- Approved suggestions may expand an existing live poll beyond the draft limit.
 insert into public.poll_options(poll_id,text,status) select multi_id,'Extra '||n,'APPROVED' from generate_series(1,8) n;
 select array_agg(id order by position,created_at,id) into ids from public.poll_options where poll_id=multi_id;
 perform public.cast_ballot(multi_id,ids);
 if cardinality(ids)<>11 or (select voter_count from public.polls where id=multi_id)<>2 or (select sum(vote_count) from public.poll_options where poll_id=multi_id)<>13 then raise exception 'Complete subset of expanded poll rejected'; end if;
 perform public.close_poll(multi_id);
 caught:=false;
 begin perform public.cast_ballot(multi_id,array[ids[1]]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Closed ballot accepted'; end if;
 reset role;
 update public.polls set closed_at=now()-interval '1 second' where id=locked_id;
 set local role authenticated;
 perform set_config('request.jwt.claim.sub',guest_id::text,true);
 select array_agg(id order by position) into ids from public.poll_options where poll_id=locked_id;
 caught:=false;
 begin perform public.cast_ballot(locked_id,array[ids[1]]); exception when raise_exception then caught:=true; end;
 if not caught then raise exception 'Expired ballot accepted'; end if;
 perform public.expire_poll(locked_id);
 if (select status from public.polls where id=locked_id)<>'CLOSED' then raise exception 'Expiry did not finalize'; end if;
 reset role;
end $test$;
rollback;
